// The i960 recompiler's offline half.
//   vf2recomp <vf2.zip> map <map out> <coverage files...>
//       the address map (assets/vf2_map.txt) from vf2run --cov runs: the program found with
//       them, its functions' entries, the indirect jumps' targets, the thunks (calls that return
//       past data). Prints how much of what ran it covers.
//   vf2recomp <vf2.zip> cpp <map> <out.cpp>
//       the program found with the map, as C++ (build/gen/vf2_rec.cpp: ROM-derived, never
//       committed), for the build's recompiled code (src/rec/i960_gen.h)
//   vf2recomp <vf2.zip> check <map> <coverage files...>
//       what of the coverage the map's program doesn't hold
#include "../../src/host/romset.h"
#include "../../src/rec/i960_analyse.h"
#include "../../src/core/mame_shim.h"
#include <algorithm>
#include <cstdio>
#include <cstring>
#include <string>

using namespace i960rec;

static const std::vector<uint8_t> *g_rom;
static uint32_t rd(uint32_t a)
{
	uint32_t v = 0;
	if (a + 4 <= g_rom->size()) memcpy(&v, &(*g_rom)[a], 4);
	return v;
}

// thunks: a call target whose call sites go on past their next instruction (inline data): a site
// that ran, whose next instruction never did, and an indirect jump or return that landed a little
// further on.
static void find_thunks(const program &p, hints &h)
{
	// the ones tools/vf2thunks knows from the code: 0x9444 and the entries before it that fall
	// into it (skip dwords to one with a top byte of 0), 0x4ec00 (8 bytes), 0x502a4 (the callee parses it)
	for (uint32_t a = 0x93c4; a <= 0x9408; a += 4) h.thunks.insert(a);
	for (uint32_t a : { 0x9444u, 0x4ec00u, 0x502a4u }) h.thunks.insert(a);
	std::set<uint32_t> landed;
	for (auto &[a, ts] : h.edges) for (uint32_t t : ts) landed.insert(t);
	std::map<uint32_t, int> votes, against;
	for (auto &[a, d] : p.insns) {
		if (d.k != kind::call || !d.has_target || !h.covered.count(a)) continue;
		const uint32_t next = a + uint32_t(d.len);
		if (h.covered.count(next)) { against[d.target]++; continue; }
		auto it = landed.lower_bound(next + 1);
		if (it != landed.end() && *it <= next + 0x200 && h.covered.count(*it)) votes[d.target]++;
	}
	for (auto &[t, n] : votes)
		if (getenv("THUNK_LOG")) fprintf(stderr, "thunk candidate %06x: %d votes, %d against\n", t, n, against.count(t) ? against[t] : 0);
	for (auto &[t, n] : votes)
		if (!against.count(t) && n >= 2) h.thunks.insert(t);
}

static void report(const program &p, const hints &h)
{
	uint64_t ran = 0, in = 0, bad = 0;
	size_t n = 0, nin = 0;
	std::map<uint32_t, uint64_t> missing;
	for (auto &[a, cnt] : h.covered) {
		ran += cnt;
		n++;
		auto it = p.insns.find(a);
		if (it != p.insns.end() && p.owner.count(a) && it->second.k != kind::bad) { in += cnt; nin++; }
		else {
			missing[a] = cnt;
			if (it != p.insns.end() && it->second.k == kind::bad) bad += cnt;
		}
	}
	size_t ninsn = 0;
	for (auto &[a, d] : p.insns) if (d.k != kind::bad) ninsn++;
	printf("%zu functions, %zu instructions (%zu not the interpreter's own: left to it)\n", p.functions.size(), ninsn, p.insns.size() - ninsn);
	printf("coverage: %zu instructions ran %llu times; recompiled %zu of them (%.4f%% of the instructions run)\n",
		   n, (unsigned long long)ran, nin, ran ? 100.0 * double(in) / double(ran) : 0.0);
	std::vector<std::pair<uint64_t, uint32_t>> top;
	for (auto &[a, c] : missing) top.push_back({ c, a });
	std::sort(top.rbegin(), top.rend());
	for (size_t i = 0; i < top.size() && i < 20; i++) printf("  not recompiled: %06x ran %llu times\n", top[i].second, (unsigned long long)top[i].first);
}

struct gen_insn { uint32_t addr, word, disp, fn; };

static int emit_cpp(const program &p, const char *out)
{
	FILE *f = fopen(out, "w");
	if (!f) { perror(out); return 1; }
	fprintf(f, "// Generated by tools/recomp/vf2recomp from the player's ROM: never commit.\n#include \"i960_gen.h\"\n\n");
	fprintf(f, "namespace {\n");
	for (size_t k = 0; k < p.functions.size(); k++) fprintf(f, "void f%zu(C &c);\n", k);
	std::vector<gen_insn> table;
	size_t n_bad = 0;
	for (size_t k = 0; k < p.functions.size(); k++) {
		const function &fn = p.functions[k];
		fprintf(f, "\n// %06x\nvoid f%zu(C &c)\n{\n", fn.entry, k);
		// spin loops' heads in this function: run from in this call (so the last time round was
		// all in this slice, not split by an interrupt that may have changed what it reads)
		std::set<uint32_t> heads;
		for (auto &[br, sp] : p.spins) if (p.owner_of(br) == int(k) && p.owner_of(sp.head) == int(k)) heads.insert(sp.head);
		for (uint32_t h : heads) fprintf(f, "\tbool spun_%x = false;\n", h);
		fprintf(f, "\tswitch (IPV) {\n");
		fprintf(f, "\tcase 0x%x: goto L_%x;\n", fn.entry, fn.entry);
		for (uint32_t a : fn.body) if (a != fn.entry && p.insns.at(a).k != kind::bad) fprintf(f, "\tcase 0x%x: goto L_%x;\n", a, a);
		fprintf(f, "\tdefault: return;\n\t}\n");
		auto go = [&](uint32_t t) -> std::string {
			const int o = p.owner_of(t);
			if (o == int(k)) return string_format("goto L_%x;", t);
			auto it = p.insns.find(t);
			if (o >= 0 && it != p.insns.end() && it->second.k != kind::bad) return string_format("TAIL(%d);", o);
			return "DISP;";
		};
		for (size_t i = 0; i < fn.body.size(); i++) {
			const uint32_t a = fn.body[i];
			const decoded &d = p.insns.at(a);
			const uint32_t next = a + uint32_t(d.len);
			const bool next_follows = i + 1 < fn.body.size() && fn.body[i + 1] == next;
			if (d.k == kind::bad) { fprintf(f, "\tBAD(%x)\n", a); n_bad++; continue; }
			table.push_back({ a, d.op, d.len == 8 ? d.disp : 0, uint32_t(k) });
			if (heads.count(a)) fprintf(f, "\tIH(%x, 0x%08x, 0x%x, %d)", a, d.op, d.len == 8 ? d.disp : 0, d.len);
			else fprintf(f, "\tI(%x, 0x%08x, 0x%x, %d)", a, d.op, d.len == 8 ? d.disp : 0, d.len);
			const uint32_t o = d.op >> 24;
			const bool may_stall = o == 0x80 || o == 0x88 || o == 0x90 || o == 0x98 || o == 0xa0 || o == 0xb0 || o == 0xc0 || o == 0xc8 ||
								   o == 0x60 || o == 0x66 || o == 0x0a;
			if (may_stall) fprintf(f, " STL");
			fprintf(f, " CHK");
			auto on = [&]() { if (!next_follows || p.owner_of(next) != int(k)) fprintf(f, " %s", go(next).c_str()); };
			switch (d.k) {
			case kind::normal:
				if (o == 0x65 || o == 0x60 || o == 0x6e) fprintf(f, " if (IPV != 0x%x) DISP;", next);   // (may take an interrupt)
				on();
				break;
			case kind::branch:
				if (auto sp = p.spins.find(a); sp != p.spins.end() && p.owner_of(d.target) == int(k)) {
					// a spin loop: round again while the cycles last, all but the last time skipped
					std::string plain = string_format(" && spun_%x", d.target);
					for (uint32_t x : sp->second.loads) plain += string_format(" && SPIN_PLAIN(0x%x)", x);
					fprintf(f, " if (IPV == 0x%x) { if (R::icount(c) > %u%s) R::icount(c) -= (R::icount(c) - 1) / %u * %u; goto L_%x; }", d.target, sp->second.cost, plain.c_str(), sp->second.cost, sp->second.cost, d.target);
				} else
					fprintf(f, " if (IPV == 0x%x) %s", d.target, go(d.target).c_str());
				if (d.target != next) on();
				break;
			case kind::jump:
				fprintf(f, " %s", go(d.target).c_str());
				break;
			case kind::call:
				if (d.has_target) fprintf(f, " %s", go(d.target).c_str());
				else fprintf(f, " DISP;");
				break;
			case kind::ijump:
				if (auto it = p.hinted.find(a); it != p.hinted.end())
					for (uint32_t t : it->second) if (p.owner_of(t) == int(k) && p.insns.at(t).k != kind::bad) fprintf(f, " if (IPV == 0x%x) goto L_%x;", t, t);
				fprintf(f, " DISP;");
				break;
			case kind::ret:
				fprintf(f, " DISP;");
				break;
			default: break;
			}
			fprintf(f, "\n");
		}
		fprintf(f, "}\n");
	}
	fprintf(f, "\n} // namespace\n\nnamespace i960rec {\nconst gen_fn gen_fns[] = {\n");
	for (size_t k = 0; k < p.functions.size(); k++) fprintf(f, "\t{ 0x%x, f%zu },\n", p.functions[k].entry, k);
	fprintf(f, "};\nconst size_t gen_nfns = %zu;\nconst gen_insn gen_insns[] = {\n", p.functions.size());
	for (const gen_insn &x : table) fprintf(f, "\t{ 0x%x, 0x%08x, 0x%x, %u },\n", x.addr, x.word, x.disp, x.fn);
	fprintf(f, "};\nconst size_t gen_ninsns = %zu;\n}\n", table.size());
	fclose(f);
	fprintf(stderr, "%s: %zu functions, %zu instructions (%zu left to the interpreter)\n", out, p.functions.size(), table.size(), n_bad);
	return 0;
}

int main(int argc, char **argv)
{
	if (argc < 4) {
		fprintf(stderr, "usage: vf2recomp <vf2.zip> map <map out> <cov...> | cpp <map> <out.cpp> | check <map> <cov...>\n");
		return 2;
	}
	romset::result roms = romset::load(argv[1]);
	if (!roms.ok) { fprintf(stderr, "%s\n", roms.error.c_str()); return 1; }
	g_rom = &roms.regions[romset::MAINCPU];
	const std::string mode = argv[2];
	const uint32_t limit = uint32_t(g_rom->size());
	if (mode == "map") {
		hints h;
		for (int i = 4; i < argc; i++) if (!h.read(argv[i])) { fprintf(stderr, "can't read %s\n", argv[i]); return 1; }
		program p = analyse(rd, limit, h);
		find_thunks(p, h);
		p = analyse(rd, limit, h);
		write_map(p, h, argv[3]);
		hints m;
		m.read(argv[3]);
		program q = analyse(rd, limit, m);   // the map's program, as the game will find it
		m.covered = h.covered;
		printf("thunks:");
		for (uint32_t t : h.thunks) printf(" %06x", t);
		printf("\n");
		report(q, m);
		return 0;
	}
	if (mode == "check") {
		hints m;
		if (!m.read(argv[3])) { fprintf(stderr, "can't read %s\n", argv[3]); return 1; }
		program q = analyse(rd, limit, m);
		for (int i = 4; i < argc; i++) { hints c; c.read(argv[i]); for (auto &[a, n] : c.covered) m.covered[a] += n; }
		report(q, m);
		return 0;
	}
	if (mode == "cpp" && argc >= 5) {
		hints m;
		if (!m.read(argv[3])) { fprintf(stderr, "can't read %s\n", argv[3]); return 1; }
		return emit_cpp(analyse(rd, limit, m), argv[4]);
	}
	fprintf(stderr, "unknown mode %s\n", mode.c_str());
	return 2;
}
