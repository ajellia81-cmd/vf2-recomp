#!/usr/bin/env python3
"""Input scripts for the recompiler's coverage runs (vf2run --cov) and the lockstep check
(vf2lock): coin up, start a game (one player, or two for versus), then random presses.
   tools/recomp/mash.py <out> <frames> [--versus] [--seed N] [--hold-start]
The script is only inputs: nothing from the ROM."""
import random, sys

out, frames = sys.argv[1], int(sys.argv[2])
versus = '--versus' in sys.argv
seed = int(sys.argv[sys.argv.index('--seed') + 1]) if '--seed' in sys.argv else 1
rng = random.Random(seed)
lines = ['# generated by tools/recomp/mash.py: %s seed %d' % ('versus' if versus else 'one player', seed), 'at 1000']
lines += ['press coin1 6', 'wait 20', 'press coin1 6', 'wait 20']
if versus: lines += ['press coin2 6', 'wait 20', 'press coin2 6', 'wait 20']
lines += ['press start1 6', 'wait 40']
if versus: lines += ['press start2 6', 'wait 40']
lines += ['wait 200', 'press p1right 4', 'wait 30', 'press p1punch 4']
if versus: lines += ['wait 10', 'press p2left 4', 'wait 30', 'press p2punch 4']
lines += ['wait 600']
moves = ['punch', 'kick', 'guard', 'down', 'up', 'left', 'right', 'punch+kick', 'guard+punch', 'down+punch', 'down+kick',
         'right+punch', 'left+kick', 'guard+kick', 'up+kick', 'right+right', 'down+guard']
f = 1000 + 1200
players = ['p1', 'p2'] if versus else ['p1']
while f < frames:
    parts = []
    for p in players:
        if rng.random() < 0.8:
            parts += ['%s%s' % (p, b) for b in rng.choice(moves).split('+')]
    # now and then a start press: continues, name entry, the next game
    if rng.random() < 0.01: parts.append('start1')
    if versus and rng.random() < 0.01: parts.append('start2')
    if rng.random() < 0.003: parts += ['coin1']
    n = rng.choice([2, 3, 4, 6, 10])
    w = rng.choice([1, 2, 3, 5, 8, 20])
    if parts:
        lines.append('press %s %d' % ('+'.join(sorted(set(parts))), n))
        f += n
    lines.append('wait %d' % w)
    f += w
open(out, 'w').write('\n'.join(lines) + '\n')
